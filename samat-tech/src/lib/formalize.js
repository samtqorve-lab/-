const PERSIAN_DICT_MAP = new Map(PERSIAN_FORMAL_DICT);
function _escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
// نگهبان مرز کلمه‌ی فارسی: مطمئن می‌شویم بلافاصله قبل/بعد از عبارت، حرف فارسی یا نیم‌فاصله
// نباشد — یعنی عبارت به‌عنوان یک کلمه‌ی مستقل تشخیص داده شود، نه تکه‌ای از وسط کلمه‌ای دیگر
// (مثلاً «کمه» در دیکشنری نباید داخل «محکمه» یا «یه» داخل «سرمایه» جایگزین شود)
const _PB = '\u0621-\u063A\u0641-\u064A\u066E-\u06D3\u200C';
const PERSIAN_COMBINED_RE = new RegExp(
  '(?<![' + _PB + '])(?:' +
  Array.from(PERSIAN_DICT_MAP.keys()).sort((a, b) => b.length - a.length).map(_escapeRe).join('|') +
  ')(?![' + _PB + '])', 'g'
);

export function formalizePersianText(text) {
  let t = text;
  t = t.replace(/ي/g, 'ی').replace(/ك/g, 'ک');
  PERSIAN_FILLERS.forEach(f => { t = t.split(f).join(''); });
  t = t.replace(/\bمی[ ]+/g, 'می‌').replace(/\bنمی[ ]+/g, 'نمی‌');
  t = t.replace(PERSIAN_COMBINED_RE, (m) => PERSIAN_DICT_MAP.get(m));
  t = t.replace(/[ \t]+([،؛؟!.,])/g, '$1');
  t = t.replace(/[ \t]{2,}/g, ' ');
  t = t.split('\n').map(line => line.trim()).filter(Boolean).join('\n');
  return t.trim();
}
