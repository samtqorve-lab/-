const EXTRA_RE = wb([...EXTRA_MAP.keys()].sort(byLen).map(esc).join('|'));
let customCache = { sig: '', map: null, re: null };
function customDict(pairs) {
  const sig = JSON.stringify(pairs);
  if (customCache.sig === sig) return customCache;
  const map = new Map(pairs);
  customCache = { sig, map, re: map.size ? wb([...map.keys()].sort(byLen).map(esc).join('|')) : null };
  return customCache;
}

function preprocess(text, customPairs) {
  let t = String(text).replace(/ي/g, 'ی').replace(/ك/g, 'ک');
  const c = customDict(customPairs);
  if (c.re) t = t.replace(c.re, (m) => c.map.get(m));
  t = t.replace(EXTRA_RE, (m) => EXTRA_MAP.get(m));
  t = t.replace(X_PRESENT_RE, (m, neg, key) => `${neg}می${Z}${xMap.get(key)}`);
  t = t.replace(X_PAST_RE, (m, neg, stem, end) => `${neg}می${Z}${stem}${X_PAST_END[end || ''] || ''}`);
  return t;
}

/** رسمی‌سازی کامل (لایه‌ی افزوده + موتور اصلی) */
export function formalizeFull(text, customPairs = loadCustomDict()) {
  return formalizePersianText(preprocess(text, customPairs));
}

/* ───────────── تحلیل تغییرات (diff) ───────────── */

const tokenize = (s) => s.split(/\s+/).filter(Boolean);

const SENT_END = /[.،؛؟!?]$/;
/** گروه کلمه‌ها را بعد از هر کلمه‌ی علامت‌دار (نقطه، ویرگول …) تکه می‌کند */
function splitAtPunct(words) {
  const parts = [];
  let cur = [];
  words.forEach((w) => { cur.push(w); if (SENT_END.test(w)) { parts.push(cur); cur = []; } });
  if (cur.length) parts.push(cur);
  return parts;
}

function makeChanges(from, to, verify) {
  const mk = (f, t) => ({ t: 'ch', from: f.join(' '), to: t.join(' '), key: `${f.join(' ')}\u0001${t.join(' ')}` });
  if (from.length > 1 && to.length > 0) {
    // اگر هر کلمه جای یک کلمه نشسته (و موتور هم همین جفت‌ها را تأیید می‌کند)، تغییرها را تک‌تک نگه دار تا جداگانه رد/قبول شوند
    if (from.length === to.length && from.every((f, i) => verify([f], [to[i]]))) return from.map((f, i) => mk([f], [to[i]]));
    // وگرنه اگر دو طرف به‌تعداد برابر جمله/بند دارند، بند به بند جفت کن
    const pf = splitAtPunct(from);
    const pt = splitAtPunct(to);
    if (pf.length > 1 && pf.length === pt.length) return pf.map((f, i) => mk(f, pt[i]));
  }
  return [mk(from, to)];
}

function middleDiff(A, B, verify) {
  const n = A.length;
  const m = B.length;
  if (!n && !m) return [];
  if (!n || !m || n * m > 3e6) return makeChanges(A, B, verify);
  const W = m + 1;
  const dp = new Uint16Array((n + 1) * W);
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      dp[i * W + j] = A[i] === B[j] ? dp[(i + 1) * W + j + 1] + 1 : Math.max(dp[(i + 1) * W + j], dp[i * W + j + 1]);
    }
  }
  const res = [];
  let fromBuf = [];
  let toBuf = [];
  let eqBuf = [];
  const flushCh = () => { if (fromBuf.length || toBuf.length) { res.push(...makeChanges(fromBuf, toBuf, verify)); fromBuf = []; toBuf = []; } };
  const flushEq = () => { if (eqBuf.length) { res.push({ t: 'eq', words: eqBuf }); eqBuf = []; } };
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (A[i] === B[j]) { flushCh(); eqBuf.push(A[i]); i += 1; j += 1; }
    else if (dp[(i + 1) * W + j] >= dp[i * W + j + 1]) { flushEq(); fromBuf.push(A[i]); i += 1; }
    else { flushEq(); toBuf.push(B[j]); j += 1; }
  }
  while (i < n) { flushEq(); fromBuf.push(A[i]); i += 1; }
  while (j < m) { flushEq(); toBuf.push(B[j]); j += 1; }
  flushCh();
  flushEq();
  return res;
}

function diffTokens(a, b, verify) {
  const out = [];
  let s = 0;
  while (s < a.length && s < b.length && a[s] === b[s]) s += 1;
  let ea = a.length;
  let eb = b.length;
  while (ea > s && eb > s && a[ea - 1] === b[eb - 1]) { ea -= 1; eb -= 1; }
  if (s) out.push({ t: 'eq', words: a.slice(0, s) });
  out.push(...middleDiff(a.slice(s, ea), b.slice(s, eb), verify));
  if (ea < a.length) out.push({ t: 'eq', words: a.slice(ea) });
  return out;
}

/** متن را رسمی می‌کند و فهرست تغییرات (قابل رد/قبول) را برمی‌گرداند */
export function analyzeText(text, customPairs = loadCustomDict()) {
  const after = formalizeFull(text, customPairs);
  const verify = (f, t) => formalizeFull(f.join(' '), customPairs) === t.join(' ');
  const segments = diffTokens(tokenize(text), tokenize(after), verify);
  const map = new Map();
  segments.forEach((s) => {
    if (s.t !== 'ch') return;
    const c = map.get(s.key);
    if (c) c.count += 1; else map.set(s.key, { key: s.key, from: s.from, to: s.to, count: 1 });
  });
  return { after, segments, changes: [...map.values()] };
}

/** متن نهایی با نادیده‌گرفتن تغییرهای ردشده (rejected = مجموعه‌ی کلیدها) */
export function composeText(segments, rejected = new Set()) {
  return segments
    .map((s) => (s.t === 'eq' ? s.words.join(' ') : (rejected.has(s.key) ? s.from : s.to)))
    .filter((x) => x !== '')
    .join(' ');
}
