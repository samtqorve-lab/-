const DICT_MAP = new Map(DICT);
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// نگهبان مرز کلمه‌ی فارسی: عبارت باید یک کلمه‌ی مستقل باشد، نه تکه‌ای از وسط کلمه‌ای دیگر
const PB = '\\u0621-\\u063A\\u0641-\\u064A\\u066E-\\u06D3\\u200C';
const COMBINED_RE = new RegExp(
  `(?<![${PB}])(?:${Array.from(DICT_MAP.keys()).sort((a, b) => b.length - a.length).map(escapeRe).join('|')})(?![${PB}])`,
  'g',
);

export function formalizePersianText(text) {
  let t = text;
  t = t.replace(/ي/g, 'ی').replace(/ك/g, 'ک');
  FILLERS.forEach((f) => { t = t.split(f).join(''); });
  t = t.replace(/\bمی[ ]+/g, 'می‌').replace(/\bنمی[ ]+/g, 'نمی‌');
  t = t.replace(COMBINED_RE, (m) => DICT_MAP.get(m));
  t = t.replace(/[ \t]+([،؛؟!.,])/g, '$1');
  t = t.replace(/[ \t]{2,}/g, ' ');
  t = t.split('\n').map((line) => line.trim()).filter(Boolean).join('\n');
  return t.trim();
}

/** مثل formalizePersianText، ولی فاصله‌ی ابتدا/انتهای متن را حفظ می‌کند (برای تکه‌متن‌های داخل HTML که کنار تگ‌های دیگر می‌نشینند) */
export function formalizeKeepingEdges(text) {
  const lead = (text.match(/^\s*/) || [''])[0];
  const trail = (text.match(/\s*$/) || [''])[0];
  const core = text.trim();
  if (!core) return text;
  return lead + formalizePersianText(core) + trail;
}
