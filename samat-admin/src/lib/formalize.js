function tidyPunctuation(t) {
  t = t.replace(/(?<=[\u0600-\u06FF])\s*,/g, '،').replace(/(?<=[\u0600-\u06FF])\s*;/g, '؛').replace(/(?<=[\u0600-\u06FF])\s*\?/g, '؟');
  t = t.replace(/[“”„]/g, '"').replace(/"([^"\n]{1,200})"/g, '«$1»');
  t = t.replace(/[ \t]+([،؛؟!])/g, '$1');
  t = t.replace(/([،؛؟!])(?=[\u0600-\u06FFA-Za-z])/g, '$1 ');
  t = t.replace(/(?<=[\u0600-\u06FF])\.(?=[\u0600-\u06FF])/g, '. ');
  t = t.replace(/([!؟?])\1+/g, '$1').replace(/،{2,}/g, '،');
  t = t.replace(/\(\s+/g, '(').replace(/\s+\)/g, ')').replace(/«\s+/g, '«').replace(/\s+»/g, '»');
  return t;
}

function fixHalfSpaces(t) {
  // نیم‌فاصله‌ی «می/نمی» حتی برای افعالی که در جدول نیستند
  t = t.replace(new RegExp(`(?<![${PB}])(ن?می) +(?=[\\u0621-\\u06CC]{2,})`, 'g'), `$1${Z}`);
  // «ها»ی جمع و «تر/ترین» و «ی» اضافه‌ی بعد از «ه»
  t = t.replace(new RegExp(`([\\u0621-\\u06CC]) +(ها|های|هایی|هایم|هایت|هایش|هایمان|هایتان|هایشان)(?![${PB}])`, 'g'), `$1${Z}$2`);
  t = t.replace(new RegExp(`([\\u0621-\\u06CC]) +(ترین|تری|تر)(?![${PB}])`, 'g'), `$1${Z}$2`);
  t = t.replace(new RegExp(`(ه) +ی(?![${PB}])`, 'g'), `$1${Z}ی`);
  // ضمیر متصل محاوره‌ای: کارشون ← کارشان
  t = t.replace(new RegExp(`(?<![${PB}])([\\u0621-\\u06CC${Z}]{2,}?)(شون|تون|مون)(?![${PB}])`, 'g'), (m, stem, suf) => {
    if (/^(همین|همان|ایمون|نشون|میمون|گوش|شیشون|نمایشگاه|دان|ریس)$/.test(stem)) return m;
    if (stem === 'ا' || stem.length < 2) return m;
    return stem + suf.replace('ون', 'ان');
  });
  return t;
}

export function formalizePersianText(text) {
  let t = String(text);
  t = t.replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/ـ/g, '').replace(/\u00a0/g, ' ').replace(/ة/g, 'ه');
  FILLERS.forEach((f) => { t = t.split(f).join(''); });

  // ۱) فرهنگ‌لغت (یک گذر هم‌زمان، تا خروجیِ یک قاعده دوباره دستکاری نشود)
  t = t.replace(DICT_RE, (m) => DICT_MAP.get(m));

  // ۲) افعال
  t = t.replace(PRESENT_RE, (m, neg, key) => `${reportPrefix(key)}${neg}می${Z}${presentMap.get(key)}`);
  t = t.replace(PAST_RE, (m, neg, stem, end) => `${neg}می${Z}${stem}${PAST_END[end || ''] || ''}`);
  t = t.replace(SUBJ_RE, (m) => subjMap.get(m));

  // «تعمیر بشود» ← «تعمیر شود» (فعل کمکی بعد از اسم، نه بعد از «اگر/که/تا ...»)
  t = t.replace(new RegExp(`(?<![${PB}])([\\u0621-\\u06CC${Z}]+) +ب(شود|شوند)(?![${PB}])`, 'g'), (m, prev, rest) => (/^(اگر|که|تا|شاید|کاش|چگونه|چه|هرچه|نگذار|بگذار|بگو|ممکن|باید)$/.test(prev) ? m : `${prev} ${rest}`));
  // ضمیر متصل «ـش» ← «ـاش» (راننده‌ش ← راننده‌اش)
  t = t.replace(new RegExp(`([\\u0621-\\u06CC])${Z}ش(?![${PB}])`, 'g'), `$1${Z}اش`);

  // ۳) صفت+ه، مفعول چسبیده، قید
  t = t.replace(ADJ_RE, (m, adj) => `${adj} است`);
  t = t.replace(OBJ_RE, (m, noun) => `${noun} را`);
  t = t.replace(ADV_RE, (m, stem) => `${stem}اً`);
  t = t.replace(new RegExp(`(?<![${PB}])رو(?![${PB}])(?=[،؛؟!.]|$|[ ]+(?:(?:هم|نیز|که|و|کرد|کردم|کردیم|کردند|کنم|کنیم|کنید|کنند|کند|انجام|بررسی|ارسال|اعلام|تعمیر|تحویل|ثبت|دریافت|پیگیری)(?![${PB}])|می${Z}|نمی${Z}))`, 'gm'), 'را');

  // ۴) نگارش
  t = fixHalfSpaces(t);
  t = tidyPunctuation(t);
  t = t.replace(/[ \t]{2,}/g, ' ');
  t = t.split('\n').map((line) => line.trim()).filter(Boolean).join('\n');
  return t.trim();
}

/** مثل formalizePersianText، ولی فاصله‌ی ابتدا/انتهای متن را حفظ می‌کند (برای تکه‌متن‌های داخل HTML که کنار تگ‌های دیگر می‌نشینند) */
export function formalizeKeepingEdges(text) {
  const lead = (text.match(/^\s*/) || [''])[0];
  const trail = (text.match(/\s*$/) || [''])[0];
  const core = text.trim();
  if (!core) return text;
  return lead + formalizePersianText(core) + trail;
}
